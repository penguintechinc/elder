@pytest.fixture
def inbound_app():
    """Minimal Quart app with webhooks blueprint and temp SQLite DAL."""
    with tempfile.NamedTemporaryFile(suffix=".db") as db_file:
        db = DAL(f"sqlite:///{db_file.name}", reflect=False, migrate=False)
        _ensure_inbound_tables(db)

        app = Quart(__name__)
        app.config["TESTING"] = True
        app.db = db

        @app.before_request
        def _inject_test_claims():
            # Allow tests to pass tenant/scopes via custom test headers so we
            # don't need full JWT/quart_cors setup for unit tests.
            tenant = None
            from quart import request

            raw_tenant = request.headers.get("X-Test-Tenant-Id")
            if raw_tenant is not None:
                tenant = raw_tenant
            raw_scopes = request.headers.get("X-Test-Scopes", "")
            scopes = [s for s in raw_scopes.split(",") if s]
            g.claims = {"tenant": tenant, "scope": " ".join(scopes)}

        app.register_blueprint(webhooks_bp, url_prefix="/api/v1/webhooks")
        yield app


def _admin_headers(tenant_id: int = 1) -> dict[str, str]:
    return {
        "X-Test-Tenant-Id": str(tenant_id),
        "X-Test-Scopes": "webhooks:read,webhooks:write,webhooks_alerting:admin",
    }


def _viewer_headers(tenant_id: int = 1) -> dict[str, str]:
    return {
        "X-Test-Tenant-Id": str(tenant_id),
        "X-Test-Scopes": "webhooks:read",
    }


@pytest.mark.asyncio
async def test_autogenerated_bearer_credentials_are_hashed(inbound_app):
    client = inbound_app.test_client()
    user = MagicMock(id=1, is_superuser=True, portal_role="admin", role="admin")

    with patch("apps.api.auth.decorators.get_current_user", return_value=user):
        resp = await client.post(
            "/api/v1/webhooks/inbound",
            json={"name": "Alertmanager Alerts"},
            headers=_admin_headers(tenant_id=1),
        )

    assert resp.status_code == 201, await resp.get_data(as_text=True)
    body = json.loads(await resp.get_data())

    webhook = body["webhook"]
    creds = body["credentials"]
    assert creds["auth_type"] == "bearer"
    assert creds["bearer_token"].startswith("wh_")
    assert webhook["receive_path"] == f"/api/v1/webhooks/receive/{webhook['slug']}"
    assert webhook["bearer_token_preview"] is not None
    assert "bearer_token_hash" not in webhook
    assert "basic_password_hash" not in webhook

    # Verify DB stores hash, never plaintext
    db = inbound_app.db
    row = db(db.inbound_webhooks.id == webhook["id"]).select().first()
    assert row is not None
    assert row.bearer_token_hash != creds["bearer_token"]
    assert check_password_hash(row.bearer_token_hash, creds["bearer_token"])


