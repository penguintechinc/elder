@pytest.mark.asyncio
async def test_receive_bearer_auth_enforced_and_headers_redacted(inbound_app):
    client = inbound_app.test_client()
    user = MagicMock(id=1, is_superuser=True, portal_role="admin", role="admin")

    with patch("apps.api.auth.decorators.get_current_user", return_value=user):
        create_resp = await client.post(
            "/api/v1/webhooks/inbound",
            json={"name": "Grafana", "auth_type": "bearer"},
            headers=_admin_headers(tenant_id=1),
        )
    created = json.loads(await create_resp.get_data())
    receive_path = created["webhook"]["receive_path"]
    token = created["credentials"]["bearer_token"]

    # Missing auth -> 401 with WWW-Authenticate
    no_auth = await client.post(receive_path, json={"alert": "high_cpu"})
    assert no_auth.status_code == 401
    assert "Bearer" in no_auth.headers.get("WWW-Authenticate", "")

    # Invalid bearer token -> 401
    bad_auth = await client.post(
        receive_path,
        json={"alert": "high_cpu"},
        headers={"Authorization": "Bearer wrong-token"},
    )
    assert bad_auth.status_code == 401

    # Valid bearer token -> 202
    ok_resp = await client.post(
        receive_path,
        json={"alert": "high_cpu", "severity": "critical"},
        headers={
            "Authorization": f"Bearer {token}",
            "X-Custom-Source": "grafana",
        },
    )
    assert ok_resp.status_code == 202, await ok_resp.get_data(as_text=True)
    ok_body = json.loads(await ok_resp.get_data())
    assert ok_body["status"] == "received"
    assert isinstance(ok_body["event_id"], int)

    # Verify stored event redacted Authorization header & updated receive_count
    with patch("apps.api.auth.decorators.get_current_user", return_value=user):
        events_resp = await client.get(
            f"/api/v1/webhooks/inbound/{created['webhook']['id']}/events",
            headers=_viewer_headers(tenant_id=1),
        )
    assert events_resp.status_code == 200
    events_body = json.loads(await events_resp.get_data())
    assert len(events_body["events"]) == 1
    ev = events_body["events"][0]
    assert ev["payload"] == {"alert": "high_cpu", "severity": "critical"}
    auth_keys = [k for k in ev["headers"] if k.lower() == "authorization"]
    assert auth_keys, "Authorization header key should be recorded as redacted"
    assert ev["headers"][auth_keys[0]] == "[REDACTED]"
    assert ev["headers"].get("X-Custom-Source") == "grafana"

    db = inbound_app.db
    row = db(db.inbound_webhooks.id == created["webhook"]["id"]).select().first()
    assert row.receive_count == 1
    assert row.last_received_at is not None


@pytest.mark.asyncio
async def test_receive_basic_auth_enforced_and_rotate_credentials(inbound_app):
    client = inbound_app.test_client()
    user = MagicMock(id=1, is_superuser=True, portal_role="admin", role="admin")

    with patch("apps.api.auth.decorators.get_current_user", return_value=user):
        create_resp = await client.post(
            "/api/v1/webhooks/inbound",
            json={"name": "GitHub", "auth_type": "basic"},
            headers=_admin_headers(tenant_id=1),
        )
    created = json.loads(await create_resp.get_data())
    webhook_id = created["webhook"]["id"]
    receive_path = created["webhook"]["receive_path"]
    u1 = created["credentials"]["username"]
    p1 = created["credentials"]["password"]

    # Missing auth -> 401 Basic
    no_auth = await client.post(receive_path, json={"event": "push"})
    assert no_auth.status_code == 401
    assert "Basic" in no_auth.headers.get("WWW-Authenticate", "")

    # Invalid basic auth -> 401
    bad_b64 = base64.b64encode(f"{u1}:wrong".encode()).decode()
    bad_auth = await client.post(
        receive_path,
        json={"event": "push"},
        headers={"Authorization": f"Basic {bad_b64}"},
    )
    assert bad_auth.status_code == 401

    # Valid basic auth -> 202
    good_b64 = base64.b64encode(f"{u1}:{p1}".encode()).decode()
    ok_resp = await client.post(
        receive_path,
        json={"event": "push"},
        headers={"Authorization": f"Basic {good_b64}"},
    )
    assert ok_resp.status_code == 202

    # Rotate credentials -> old creds fail, new creds succeed
    with patch("apps.api.auth.decorators.get_current_user", return_value=user):
        rot_resp = await client.post(
            f"/api/v1/webhooks/inbound/{webhook_id}/rotate-credentials",
            headers=_admin_headers(tenant_id=1),
        )
    assert rot_resp.status_code == 200
    rot_body = json.loads(await rot_resp.get_data())
    u2 = rot_body["credentials"]["username"]
    p2 = rot_body["credentials"]["password"]
    assert (u2, p2) != (u1, p1)

    old_after_rot = await client.post(
        receive_path,
        json={"event": "push"},
        headers={"Authorization": f"Basic {good_b64}"},
    )
    assert old_after_rot.status_code == 401

    new_b64 = base64.b64encode(f"{u2}:{p2}".encode()).decode()
    new_after_rot = await client.post(
        receive_path,
        json={"event": "push"},
        headers={"Authorization": f"Basic {new_b64}"},
    )
    assert new_after_rot.status_code == 202


@pytest.mark.asyncio
async def test_inbound_webhook_tenant_isolation_and_lifecycle(inbound_app):
    client = inbound_app.test_client()
    user = MagicMock(id=1, is_superuser=True, portal_role="admin", role="admin")

    with patch("apps.api.auth.decorators.get_current_user", return_value=user):
        create_resp = await client.post(
            "/api/v1/webhooks/inbound",
            json={"name": "Tenant1 Hook"},
            headers=_admin_headers(tenant_id=1),
        )
        assert create_resp.status_code == 201
        created = json.loads(await create_resp.get_data())
        wid = created["webhook"]["id"]
        receive_path = created["webhook"]["receive_path"]
        token = created["credentials"]["bearer_token"]

        # Tenant 2 cannot see, update, rotate, view events, or delete Tenant 1's hook
        list_t2 = await client.get(
            "/api/v1/webhooks/inbound", headers=_viewer_headers(tenant_id=2)
        )
        assert list_t2.status_code == 200
        assert json.loads(await list_t2.get_data())["inbound_webhooks"] == []

        put_t2 = await client.put(
            f"/api/v1/webhooks/inbound/{wid}",
            json={"name": "Hijack"},
            headers=_admin_headers(tenant_id=2),
        )
        assert put_t2.status_code == 404

        del_t2 = await client.delete(
            f"/api/v1/webhooks/inbound/{wid}",
            headers=_admin_headers(tenant_id=2),
        )
        assert del_t2.status_code == 404

        # Disable hook -> receive returns 404
        disable_resp = await client.put(
            f"/api/v1/webhooks/inbound/{wid}",
            json={"is_active": False},
            headers=_admin_headers(tenant_id=1),
        )
        assert disable_resp.status_code == 200
        assert (
            json.loads(await disable_resp.get_data())["webhook"]["is_active"] is False
        )

        disabled_receive = await client.post(
            receive_path,
            json={"test": 1},
            headers={"Authorization": f"Bearer {token}"},
        )
        assert disabled_receive.status_code == 404

        # Delete hook
        del_t1 = await client.delete(
            f"/api/v1/webhooks/inbound/{wid}",
            headers=_admin_headers(tenant_id=1),
        )
        assert del_t1.status_code == 200
